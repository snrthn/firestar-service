<p>除下列情形外，我们不会向任何第三方共享您的个人信息：事先获得您的明示同意；为订立、履行您作为一方当事人的合同所必需；为履行法定义务所必需，或应司法机关、行政机关依法作出的强制性要求；法律、行政法规规定的其他情形。</p>
<p>我们当前接入的服务商仅限于：</p>
<ul>
<li>阿里云对象存储服务（OSS）：用于存储和分发您上传的附件、凭证等文件；</li>
<li>阿里云云服务器（ECS）：用于部署与运行本服务。</li>
</ul>
<p>除上述之外，本服务当前<strong>未接入</strong>任何第三方支付、短信验证、地图定位、数据统计或广告营销类服务或软件开发工具包。若后续新增此类接入，我们将更新本隐私政策并通过本服务公告告知您，必要时会再次征得您的同意。</p>

<h3>（二）转让</h3>
<p>除发生合并、分立、清算等情形确需转移个人信息（届时我们将告知接收方的名称和联系方式，并要求其继续受本政策约束；变更原处理目的者将重新征得您的同意）外，我们不会向任何第三方转让您的个人信息。</p>

<h3>（三）公开披露</h3>
<p>原则上我们不公开披露您的个人信息。如确有必要公开披露，我们会在告知您披露的目的、信息类型与接收方并取得您的明示同意后实施。</p>

<h2>四、信息的存储地域与存储期限</h2>
<ul>
<li>存储地域：我们在中华人民共和国境内运营中收集和产生的个人信息，均存储在中华人民共和国境内的服务器与存储空间中。我们不会将上述信息向境外提供。</li>
<li>存储期限：我们仅在实现本政策所述目的所必需的期间，以及法律法规要求的最短留存期限内保留您的个人信息。超出上述期限后，我们将对您的个人信息进行删除或匿名化处理。</li>
</ul>

<h2>五、我们如何保护您的信息安全</h2>
<ul>
<li>传输安全：本服务全站启用 HTTPS 加密传输。</li>
<li>存储安全：用户密码经 BCrypt 加盐哈希后存储，不以明文形式保存。</li>
<li>访问控制：采用基于角色的权限控制并辅以行级数据隔离，按照最小授权原则限制接触范围，列表与详情接口均实施数据归属校验。</li>
<li>审计机制：完整记录登录日志与关键操作日志，支持事后追溯。</li>
<li>应急处置：我们已制定个人信息安全事件应急预案。若发生安全事件，我们将按照法律法规要求及时启动预案，向您告知事件的基本情况与影响、已采取的措施、自主防范与降低风险的建议以及补救措施，并向有关主管部门报告。</li>
</ul>
<p>互联网环境并非绝对安全，我们将持续努力提升安全防护水平，但也请您妥善保管账号、密码等信息，避免因自身原因导致的信息泄露。</p>

