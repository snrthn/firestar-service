-- ============================================================================
-- V212：重建 sys_kb_chunk 全文索引，修复"数据已导入但 MATCH 召回为空"的存量问题
--
-- 背景（2026-11-17 P0-1 真机验收实测发现）：
--   sys_kb_chunk 的 FULLTEXT(ngram) 索引在批量导入/迁移数据后可能处于未同步状态：
--   MATCH(content, heading_path) AGAINST(...) IN BOOLEAN MODE 恒返回 0，
--   但同结构新建表灌入相同数据立刻能召回；OPTIMIZE TABLE 重建后原表恢复正常。
--   这是 InnoDB 全文索引的同步状态问题，非业务数据错误。
--
-- 为什么放迁移里：
--   存量库（已部署、索引已不同步）不会有人手动跑运维脚本，但每次升级必然执行 Flyway。
--   本迁移保证"升级到 V212 的库"全文索引被强制重建一次；幂等，可安全重复。
--
-- 与运维脚本的分工（bin/rebuild-kb-ft-index.sh）：
--   本迁移  = 一次性的存量修复（升级自动执行，覆盖已部署环境）
--   运维脚本 = 可重复执行（覆盖"未来每次批量导入/迁移之后"，按需或纳入部署流程）
--
-- 注意：OPTIMIZE TABLE 对 InnoDB 等价 ALTER TABLE ... FORCE，MySQL 会隐式提交；
--       大表会重建并短时锁表。若生产库该表数据量很大，请在低峰期升级，
--       或跳过本迁移、改由运维脚本在低峰期单独执行。
--       （本表为知识库切片，量级通常可控；空表执行无副作用。）
-- ============================================================================
OPTIMIZE TABLE `sys_kb_chunk`;
